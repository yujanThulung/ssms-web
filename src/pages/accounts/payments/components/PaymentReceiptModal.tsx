import { useCallback, useEffect, useMemo, useRef, useState } from 'react'
import { Modal, Button, Space, Typography, Spin, Alert, message } from 'antd'
import { Printer, Download, ReceiptText } from 'lucide-react'
import { colors } from '../../../../lib/designTokens'
import {
  usePayment,
  useDownloadReceipt,
  useReceiptPdf,
  fetchReceiptPdfBlob,
  printPdfBlob,
  printReceipt,
  type Payment,
} from '../../../../features/payments'
import schoolLogo from '../../../../assets/logo.png'

const { Text } = Typography

interface PaymentReceiptModalProps {
  /**
   * The payment whose receipt should be shown. A full object is preferred
   * (e.g. a freshly created payment); partial/list data is hydrated
   * automatically via the payments detail endpoint.
   */
  payment: Payment | null
  open: boolean
  onClose: () => void
  /** Open the browser print dialog automatically (invoice flow behaviour). */
  autoPrint?: boolean
}

export function PaymentReceiptModal({
  payment,
  open,
  onClose,
  autoPrint = false,
}: PaymentReceiptModalProps) {
  const [isPrinting, setIsPrinting] = useState(false)
  const hasAutoPrintedRef = useRef(false)

  // Hydrate the full payment record (list rows only carry partial data)
  const { data: fullPayment } = usePayment(payment?.id, open)

  // Official backend PDF
  const { data: pdfBlob, error: pdfError } = useReceiptPdf(payment?.id, open)

  const { mutateAsync: downloadReceipt, isPending: isDownloading } = useDownloadReceipt()

  const pdfUrl = useMemo(
    () => (pdfBlob ? window.URL.createObjectURL(pdfBlob) : null),
    [pdfBlob],
  )

  // Free the object URL when it is replaced or on unmount (external cleanup only)
  useEffect(() => {
    return () => {
      if (pdfUrl) window.URL.revokeObjectURL(pdfUrl)
    }
  }, [pdfUrl])

  const handlePrint = useCallback(async () => {
    if (!payment) return
    setIsPrinting(true)
    try {
      // Always print from the backend-generated PDF for consistency
      const blob = pdfBlob ?? (await fetchReceiptPdfBlob(payment.id))
      await printPdfBlob(blob)
    } catch {
      // Fallback: client-side receipt (only possible with full payment data)
      const fallback = fullPayment ?? payment
      try {
        await printReceipt(fallback, schoolLogo)
      } catch {
        message.error('Failed to open print dialog')
      }
    } finally {
      setIsPrinting(false)
    }
  }, [payment, fullPayment, pdfBlob])

  // Auto-print once the PDF is ready (like the invoice flow)
  useEffect(() => {
    if (open && pdfUrl && autoPrint && !hasAutoPrintedRef.current) {
      hasAutoPrintedRef.current = true
      const timer = setTimeout(() => {
        handlePrint()
      }, 400)
      return () => clearTimeout(timer)
    }
  }, [open, pdfUrl, autoPrint, handlePrint])

  // Reset the auto-print flag after the modal finishes closing (event handler)
  const handleAfterOpenChange = useCallback((visible: boolean) => {
    if (!visible) {
      hasAutoPrintedRef.current = false
    }
  }, [])

  const handleDownloadPdf = async () => {
    if (!payment) return
    try {
      await downloadReceipt({
        paymentId: payment.id,
        paymentNumber: payment.paymentNumber,
      })
      message.success('Receipt PDF downloaded successfully')
    } catch (err: unknown) {
      message.error(err instanceof Error ? err.message : 'Failed to download receipt PDF')
    }
  }

  if (!payment) return null

  return (
    <Modal
      open={open}
      onCancel={onClose}
      afterOpenChange={handleAfterOpenChange}
      width={860}
      destroyOnClose
      title={
        <div style={{ display: 'flex', alignItems: 'center', gap: 8 }}>
          <ReceiptText size={18} color={colors.success} />
          <span style={{ fontWeight: 600 }}>Payment Receipt — {payment.paymentNumber}</span>
        </div>
      }
      footer={
        <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center' }}>
          <Text type="secondary" style={{ fontSize: 12 }}>
            Official receipt PDF generated by the system
          </Text>
          <Space>
            <Button onClick={onClose}>Close</Button>
            <Button
              icon={<Download size={15} />}
              onClick={handleDownloadPdf}
              loading={isDownloading}
            >
              Download PDF
            </Button>
            <Button
              type="primary"
              icon={<Printer size={15} />}
              onClick={handlePrint}
              loading={isPrinting}
              style={{ backgroundColor: colors.success, borderColor: colors.success }}
            >
              Print
            </Button>
          </Space>
        </div>
      }
    >
      {pdfError ? (
        <Alert
          type="error"
          showIcon
          message="Could not load the receipt PDF"
          description={pdfError.message}
          style={{ marginBottom: 12 }}
        />
      ) : !pdfUrl ? (
        <div
          style={{
            display: 'flex',
            flexDirection: 'column',
            alignItems: 'center',
            justifyContent: 'center',
            padding: '72px 0',
            gap: 12,
          }}
        >
          <Spin size="large" />
          <Text type="secondary">Preparing receipt PDF…</Text>
        </div>
      ) : (
        <iframe
          src={pdfUrl}
          title={`Receipt ${payment.paymentNumber}`}
          style={{
            width: '100%',
            height: '68vh',
            border: `1px solid ${colors.border}`,
            borderRadius: 8,
            backgroundColor: '#f5f5f5',
            display: 'block',
          }}
        />
      )}
    </Modal>
  )
}
